func checkPathNotice(installedPath string) {
	dir := filepath.Dir(installedPath)
	pathEnv := os.Getenv("PATH")
	paths := filepath.SplitList(pathEnv)
	inPath := false
	for _, p := range paths {
		if filepath.Clean(p) == filepath.Clean(dir) {
			inPath = true
			break
		}
	}
	if !inPath {
		fmt.Printf("\n提示: 目录 %s 似乎不在您的 PATH 环境变量中。\n", dir)
		if runtime.GOOS == "darwin" || runtime.GOOS == "linux" {
			fmt.Printf("建议在 ~/.zshrc 或 ~/.bashrc 中添加：\n  export PATH=\"%s:$PATH\"\n", dir)
		}
	} else {
		fmt.Println("现在您可以在任意终端中使用 `xylring .` 打开当前 Git 仓库。")
	}
}

// findCurrentAppPath 检测当前运行程序的 app bundle 路径和可执行文件路径。
func findCurrentAppPath() (appBundle string, appBin string) {
	exe, err := os.Executable()
	if err != nil {
		return "", ""
	}
	// 解析软链接得到真实的二进制位置
	if realExe, err := filepath.EvalSymlinks(exe); err == nil {
		exe = realExe
	}
	appBin = exe

	// 如果是在 macOS .app 内运行，提取 .app 目录
	cleanPath := filepath.ToSlash(exe)
	if idx := strings.Index(cleanPath, ".app/Contents/MacOS/"); idx != -1 {
		appBundle = filepath.FromSlash(cleanPath[:idx+4])
	}
	return appBundle, appBin
}

// generateCLIScriptContent 生成 unix 系统的 shell launcher 脚本内容。
func generateCLIScriptContent(appBundle, appBin string) string {
	return fmt.Sprintf(`#!/usr/bin/env bash
# Xylring CLI Launcher (Generated by Xylring)

TARGET_APP="%s"
TARGET_BIN="%s"

# 检查目标应用是否存在，若被移动则在常见位置搜寻
if [ ! -d "$TARGET_APP" ] && [ ! -x "$TARGET_BIN" ]; then
    if [ -d "/Applications/Xylring.app" ]; then
        TARGET_APP="/Applications/Xylring.app"
        TARGET_BIN="/Applications/Xylring.app/Contents/MacOS/Xylring"
    elif [ -d "$HOME/Applications/Xylring.app" ]; then
        TARGET_APP="$HOME/Applications/Xylring.app"
        TARGET_BIN="$HOME/Applications/Xylring.app/Contents/MacOS/Xylring"
    fi
fi

# 常用查询与安装子命令直接由二进制处理，避免启动 GUI
case "$1" in
    -h|--help|-v|--version|version|help|install-cli|uninstall-cli|stamp|ring)
        if [ -x "$TARGET_BIN" ]; then
            exec "$TARGET_BIN" "$@"
        fi
        ;;
esac

# 将参数中的目录与文件路径转换为标准绝对路径
ARGS=()
for arg in "$@"; do
    if [[ "$arg" == -* ]]; then
        ARGS+=("$arg")
    elif [ -d "$arg" ]; then
        ABS_DIR="$(cd "$arg" 2>/dev/null && pwd)"
        ARGS+=("$ABS_DIR")
    elif [ -f "$arg" ]; then
        DIR="$(cd "$(dirname "$arg")" 2>/dev/null && pwd)"
        ARGS+=("$DIR/$(basename "$arg")")
    else
        ARGS+=("$arg")
    fi
done

# 在 macOS 上如果存在 App Bundle，优先使用 open 命令打开，即刻释放终端并激活前台
if [ "$(uname -s)" = "Darwin" ] && [ -d "$TARGET_APP" ]; then
    if [ ${#ARGS[@]} -eq 0 ]; then
        open -a "$TARGET_APP"
    else
        open -a "$TARGET_APP" "${ARGS[@]}"
    fi
    exit 0
fi

# 否则直接调用可执行文件（具备单实例检测与唤醒能力）
if [ -x "$TARGET_BIN" ]; then
    exec "$TARGET_BIN" "${ARGS[@]}"
fi

echo "错误: 未找到 Xylring 可执行程序 ($TARGET_BIN)" >&2
exit 1
`, appBundle, appBin)
}

func generateWindowsCmdContent(appBin string) string {
	return fmt.Sprintf(`@echo off
REM Xylring CLI Launcher for Windows
for %%%%C in (stamp ring install-cli uninstall-cli version help -h --help -v --version) do if "%%~1"=="%%%%C" goto cli
start "" "%s" %%*
exit /b
:cli
"%s" %%*
exit /b %%errorlevel%%
`, appBin, appBin)
}

func isDirWritableOrCreatable(dir string) bool {
	if dir == "" {
		return false
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return false
	}
	testFile := filepath.Join(dir, fmt.Sprintf(".xylring-write-test-%d", os.Getpid()))
	if err := os.WriteFile(testFile, []byte(""), 0o644); err != nil {
		return false
	}
	_ = os.Remove(testFile)
	return true
}

// getCandidateBinDirs 返回系统建议安装命令行工具的目录列表（按优先级排列）。
func getCandidateBinDirs() []string {
	var candidates []string
	home, _ := os.UserHomeDir()
	pathEnv := os.Getenv("PATH")
	paths := filepath.SplitList(pathEnv)

	if runtime.GOOS == "windows" {
		localApp := os.Getenv("LOCALAPPDATA")
		if localApp != "" {
			candidates = append(candidates, filepath.Join(localApp, "Microsoft", "WindowsApps"))
		}
		if home != "" {
			candidates = append(candidates, filepath.Join(home, "bin"))
		}
		return candidates
	}

	standardDirs := []string{}
	if home != "" {
		standardDirs = append(standardDirs, filepath.Join(home, ".local", "bin"))
		standardDirs = append(standardDirs, filepath.Join(home, "bin"))
	}
	standardDirs = append(standardDirs, "/usr/local/bin")

	// 优先选择既在标准列表、又在 PATH 中且可写的目录
	for _, dir := range standardDirs {
		if slices.Contains(paths, dir) {
			candidates = append(candidates, dir)
		}
	}
	// 其次是其余标准目录
	for _, dir := range standardDirs {
		if !slices.Contains(candidates, dir) {
			candidates = append(candidates, dir)
		}
	}
	return candidates
}

// installCLITool 将 xylring 命令行工具安装到合适的系统 PATH 目录。
func installCLITool() (string, error) {
	appBundle, appBin := findCurrentAppPath()
	if appBin == "" {
		return "", errors.New("无法确定当前 Xylring 可执行文件的位置")
	}

	candidates := getCandidateBinDirs()
	var targetDir string
	for _, dir := range candidates {
		if isDirWritableOrCreatable(dir) {
			targetDir = dir
			break
		}
	}

	if targetDir == "" {
		return "", errors.New("未找到可写入的 bin 目录，请检查权限（如 ~/.local/bin 或 /usr/local/bin）")
	}

	cmdName := "xylring"
	if runtime.GOOS == "windows" {
		cmdName = "xylring.cmd"
		content := generateWindowsCmdContent(appBin)
		targetFile := filepath.Join(targetDir, cmdName)
		if err := os.WriteFile(targetFile, []byte(content), 0o755); err != nil {
			return "", err
		}
		return targetFile, nil
	}

	scriptContent := generateCLIScriptContent(appBundle, appBin)
	targetFile := filepath.Join(targetDir, cmdName)
	if err := os.WriteFile(targetFile, []byte(scriptContent), 0o755); err != nil {
		return "", err
	}
	return targetFile, nil
}

// uninstallCLITool 从系统候选目录中移除已安装的 xylring 命令。
func uninstallCLITool() (string, error) {
	candidates := getCandidateBinDirs()
	cmdName := "xylring"
	if runtime.GOOS == "windows" {
		cmdName = "xylring.cmd"
	}

	var removed []string
	for _, dir := range candidates {
		file := filepath.Join(dir, cmdName)
		data, err := os.ReadFile(file)
		if err != nil {
			continue
		}
		// 校验文件是否包含 Xylring 标记，避免误删
		if strings.Contains(string(data), "Xylring") {
			if err := os.Remove(file); err == nil {
				removed = append(removed, file)
			}
		}
	}

	if len(removed) == 0 {
		return "", errors.New("未在常见目录中找到已安装的 xylring 命令行工具")
	}
	return strings.Join(removed, ", "), nil
}

func (a *app) installCLIMenu() {
	path, err := installCLITool()
	if err != nil {
		a.setBanner(fmt.Sprintf("安装命令行工具失败: %v", err), "")
		return
	}
	a.notifySuccess(nil, fmt.Sprintf("已成功安装 'xylring' 命令到: %s", path))
}

func (a *app) uninstallCLIMenu() {
	path, err := uninstallCLITool()
	if err != nil {
		a.setBanner(fmt.Sprintf("卸载命令行工具失败: %v", err), "")
		return
	}
	a.notifySuccess(nil, fmt.Sprintf("已成功卸载命令行工具 (%s)", path))
}
