const defaultVersion = "0.7.0"

func getAppVersion() string {
	if v := mygo.App.Version(); v != "" {
		return v
	}
	return defaultVersion
}

// normalizePaths 将命令行传入的路径参数清洗为绝对路径。
// 过滤掉以 "-" 开头的命令行标志。
func normalizePaths(args []string, workingDir string) []string {
	if workingDir == "" {
		if wd, err := os.Getwd(); err == nil {
			workingDir = wd
		}
	}
	var paths []string
	for _, arg := range args {
		arg = strings.TrimSpace(arg)
		if arg == "" || strings.HasPrefix(arg, "-") {
			continue
		}
		target := arg
		if !filepath.IsAbs(target) && workingDir != "" {
			target = filepath.Join(workingDir, target)
		}
		target = filepath.Clean(target)
		paths = append(paths, target)
	}
	return paths
}

// handleCLIArgs 处理命令行独立选项（如 --version, --help, install-cli 等）。
// 若返回 true，表示该命令已在终端完成处理，主程序无需进入 GUI 模式，应直接退出。
func handleCLIArgs(args []string) bool {
	if len(args) == 0 {
		return false
	}
	first := args[0]
	switch first {
	case "stamp", "ring":
		dir, err := os.Getwd()
		if err == nil {
			err = runRingCLI(context.Background(), dir, args, os.Stdout)
		}
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		return true
	case "-v", "--version", "version":
		fmt.Printf("Xylring version %s\n", getAppVersion())
		return true

	case "-h", "--help", "help":
		printCLIHelp()
		return true

	case "install-cli":
		installed, err := installCLITool()
		if err != nil {
			fmt.Fprintf(os.Stderr, "安装失败: %v\n", err)
			os.Exit(1)
		}
		fmt.Printf("成功将 'xylring' 命令行工具安装到: %s\n", installed)
		checkPathNotice(installed)
		return true

	case "uninstall-cli":
		removed, err := uninstallCLITool()
		if err != nil {
			fmt.Fprintf(os.Stderr, "卸载失败: %v\n", err)
			os.Exit(1)
		}
		fmt.Printf("成功卸载 'xylring' 命令行工具: %s\n", removed)
		return true
	}
	return false
}

